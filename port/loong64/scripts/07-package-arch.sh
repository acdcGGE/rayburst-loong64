#!/usr/bin/env bash
# Build an Arch Linux / pacman package for Loong Arch Linux (CARCH=loong64).
#
# The payload is the SAME tree that scripts/06-package-deb.sh stages, so the
# .deb and .pkg.tar.zst contain byte-identical files. If the stage is missing,
# 06 is run first (it also produces the .deb).
#
# Arch package layout (makepkg / libalpm):
#   .PKGINFO                     mandatory metadata
#   .MTREE                       gzip'ed mtree of the payload (file checks)
#   usr/...                      payload, root-owned
#   <name>-<pkgver>-<pkgrel>-<arch>.pkg.tar.zst
#
# .BUILDINFO is intentionally absent: it is produced by makepkg from a
# PKGBUILD build environment. This recipe archives already-built artifacts,
# which is equivalent to makepkg's package() stage, so no build environment
# metadata can honestly be claimed. pacman does not require .BUILDINFO.
set -euo pipefail
. "$(dirname -- "$0")/../env.sh"

for c in bsdtar zstd gzip node; do
  command -v "$c" >/dev/null 2>&1 || { echo "[07] FATAL: $c not found"; exit 1; }
done

UPSTREAM_VERSION="$(node -e "console.log(require('$SRC/package.json').version)")"
# Arch pkgver must not contain a hyphen (it separates pkgver from pkgrel).
PKGVER="${UPSTREAM_VERSION//-/_}"
PKGREL="${PKGREL:-1}"
# Loong Arch Linux maps uname's loongarch64 -> pacman CARCH "loong64".
PKGARCH="${PKGARCH:-loong64}"
PACKAGER="${PACKAGER:-loong64 port <port@localhost>}"

OUT="$PORT_ROOT/dist"
STAGE="$OUT/deb-stage"
PKG="$OUT/rayburst-${PKGVER}-${PKGREL}-${PKGARCH}.pkg.tar.zst"

# --- payload -------------------------------------------------------------
if [ ! -x "$STAGE/usr/bin/rayburst" ]; then
  echo "[07] stage missing -> running 06-package-deb.sh first"
  "$PORT_ROOT/scripts/06-package-deb.sh"
fi
for f in rayburst aria2-next rayburst-browser-launcher; do
  test -x "$STAGE/usr/bin/$f" || { echo "[07] FATAL: missing $STAGE/usr/bin/$f"; exit 1; }
done

# deb-stage is created with the caller's umask (775/664). Normalise to the
# usual Arch layout before recording permissions in .MTREE.
find "$STAGE/usr" -type d -exec chmod 0755 {} +
find "$STAGE/usr" -type f -exec chmod 0644 {} +
chmod 0755 "$STAGE/usr/bin/rayburst" \
           "$STAGE/usr/bin/aria2-next" \
           "$STAGE/usr/bin/rayburst-browser-launcher"

mkdir -p "$OUT"

# --- .PKGINFO ------------------------------------------------------------
SIZE="$(du -sb "$STAGE/usr" | cut -f1)"
BUILDDATE="$(date +%s)"

# Only direct, unambiguous dependencies. webkit2gtk-4.1 pulls in the
# gstreamer / soup / cairo stack on Arch; ldd on the main binary shows no
# libayatana-appindicator (the tray uses Rust ksni over D-Bus).
# Override for a different port's naming with: ARCH_DEPENDS="pkg1 pkg2 ..."
if [ -n "${ARCH_DEPENDS:-}" ]; then
  read -r -a DEPS <<< "$ARCH_DEPENDS"
else
  DEPS=(webkit2gtk-4.1 gtk3 libsoup3 librsvg libglvnd hicolor-icon-theme)
fi

{
  echo "# Generated by rayburst-loong64/scripts/07-package-arch.sh"
  echo "pkgname = rayburst"
  echo "pkgbase = rayburst"
  echo "pkgver = ${PKGVER}-${PKGREL}"
  echo "pkgdesc = Modern download manager built with Tauri 2 (LoongArch64 port)"
  echo "url = https://github.com/AnInsomniacy/rayburst"
  echo "builddate = $BUILDDATE"
  echo "packager = $PACKAGER"
  echo "size = $SIZE"
  echo "arch = $PKGARCH"
  echo "license = MIT"
  echo "license = GPL-2.0-or-later"
  for d in "${DEPS[@]}"; do echo "depend = $d"; done
} > "$STAGE/.PKGINFO"
chmod 0644 "$STAGE/.PKGINFO"

# --- .MTREE --------------------------------------------------------------
# Same keyword set makepkg uses. Owner overrides keep the mtree consistent
# with the root-owned entries written into the archive below. -n makes the
# gzip header reproducible.
MTREE_OPTS='!all,use-set,type,uid,gid,mode,time,size,link,sha256digest'
( cd "$STAGE" && bsdtar -cf - --format=mtree --options="$MTREE_OPTS" \
    --uid 0 --gid 0 --uname root --gname root .PKGINFO usr ) \
  | gzip -n -9 > "$STAGE/.MTREE"
chmod 0644 "$STAGE/.MTREE"

# --- archive -------------------------------------------------------------
# pax-restricted tar (bsdtar default) + zstd, metadata first like makepkg.
( cd "$STAGE" && bsdtar --uid 0 --gid 0 --uname root --gname root \
    -cf - .MTREE .PKGINFO usr ) \
  | zstd -q -9 -T0 -f -o "$PKG"

echo "[07] package: $PKG"
echo "[07] upstream version: $UPSTREAM_VERSION (pkgver=$PKGVER-$PKGREL, arch=$PKGARCH)"
echo "[07] entries: $(bsdtar -tf "$PKG" | wc -l)"
bsdtar -tvf "$PKG" | head -6
echo "[07] .PKGINFO:"
bsdtar -xOf "$PKG" .PKGINFO | sed 's/^/       /'
echo "[07] OK"
